#!/usr/bin/env python3
"""
Renders 11_BRAIN/06_IDEA_TO_SCRIPT.md from 12_PROGRAM/IDEA_TO_SCRIPT_MATRIX.json.

The document is GENERATED, never hand-written, so it cannot drift away from the
measurements it claims to report. Every cell in the output is read out of the
matrix; nothing is asserted here that is not derived there.

Why this exists: a correlation document written by hand starts agreeing with
itself and stops agreeing with the code. Every claim below is a lookup.

Idempotent: same matrix in, byte-identical document out, apart from the
generated-on date taken from the matrix itself (not from the clock), so a
re-run does not produce a spurious diff.

Usage: python 08_SELF_IMPROVEMENT\\build_idea_to_script_doc.py
"""
import io
import json
import sys
from collections import Counter, OrderedDict
from pathlib import Path
from typing import Any, Dict, List

WORKSPACE = Path(__file__).resolve().parent.parent
MATRIX_JSON = WORKSPACE / '12_PROGRAM' / 'IDEA_TO_SCRIPT_MATRIX.json'
GAPS_JSON = WORKSPACE / '12_PROGRAM' / 'GAP_REGISTER.json'
OUT_MD = WORKSPACE / '11_BRAIN' / '06_IDEA_TO_SCRIPT.md'

STATUS_ORDER = ['WIRED', 'OBSERVABLE', 'TESTED', 'CODED', 'PARTIAL', 'DESIGNED']

STATUS_MEANING = OrderedDict([
    ('WIRED', 'reachable through an MCP tool or a live runtime'),
    ('OBSERVABLE', 'surfaced by the monitor or a Command Center panel'),
    ('TESTED', 'a test exists and ran green'),
    ('CODED', 'implementation exists, no covering test'),
    ('PARTIAL', 'some of the chain exists, the rest does not'),
    ('DESIGNED', 'doctrine exists, no implementation'),
])


def link(path_text, exists: bool) -> str:
    """Render a repo-relative path as a link, or as plain text when absent."""
    if not path_text:
        return '-'
    if exists:
        return '[`%s`](../%s)' % (path_text, path_text)
    return '`%s` **MISSING**' % path_text


def yesno(flag) -> str:
    return 'yes' if flag else 'no'


def render(matrix: List[Dict[str, Any]], gaps: List[Dict[str, Any]], meta) -> str:
    out = []
    a = out.append

    a('# 06 - IDEA to SCRIPT correlation')
    a('')
    a('> GENERATED FILE. Source: [`../12_PROGRAM/IDEA_TO_SCRIPT_MATRIX.json`]'
      '(../12_PROGRAM/IDEA_TO_SCRIPT_MATRIX.json), rendered by '
      '`../08_SELF_IMPROVEMENT/build_idea_to_script_doc.py`.')
    a('> Do not edit this file. Change the matrix (or the code the matrix measures) and re-run '
      'the renderer - otherwise the document starts describing a system that no longer exists.')
    a('')

    a('## What this document answers')
    a('')
    a('For every concept SENTINEL is built on: where the idea was written down, which script '
      'implements it, whether a test covers it, whether an MCP tool exposes it, and which Command '
      'Center panel shows it. The chain is `idea -> doctrine -> script -> test -> MCP -> panel`, '
      'and a break anywhere in the chain is a gap, not a detail.')
    a('')

    # ---------------------------------------------------------------- summary
    counts = Counter(c.get('status', 'UNKNOWN') for c in matrix)
    a('## Status distribution')
    a('')
    a('| Status | Count | Meaning |')
    a('|---|---|---|')
    for status in STATUS_ORDER:
        if counts.get(status):
            a('| `%s` | %d | %s |' % (status, counts[status], STATUS_MEANING[status]))
    for status in sorted(counts):
        if status not in STATUS_MEANING:
            a('| `%s` | %d | (not classified by the matrix builder) |' % (status, counts[status]))
    a('| **total** | **%d** | |' % len(matrix))
    a('')

    a('A status is a *measurement*, not a grade. `DESIGNED` on the partnership protocol is not a '
      'failure of the build - it is the operator\'s own wisdom layer, deliberately left as text. '
      'It is listed so it cannot be mistaken for something running.')
    a('')

    # ------------------------------------------------------- the full matrix
    a('## The correlation matrix')
    a('')
    a('| ID | Concept | Chapter | Doctrine | Implementation | Symbols | Test | MCP | Panel | Status |')
    a('|---|---|---|---|---|---|---|---|---|---|')
    for c in matrix:
        symbols = c.get('symbols') or []
        missing = c.get('symbols_missing') or []
        sym_txt = ', '.join('`%s`' % s for s in symbols) if symbols else '-'
        if missing:
            sym_txt += ' &nbsp;**missing:** ' + ', '.join('`%s`' % s for s in missing)
        test = c.get('test')
        test_txt = ('`%s`' % test) if test and c.get('test_found') else '**none**'
        if test and not c.get('test_found'):
            test_txt = '`%s` **MISSING**' % test
        mcp = c.get('mcp_tool')
        mcp_txt = ', '.join('`%s`' % m.strip() for m in mcp.split(',')) if mcp else '-'
        if mcp and not c.get('mcp_wired'):
            mcp_txt += ' &nbsp;*(declared, not wired)*'
        a('| `%s` | %s | `%s` | %s | %s | %s | %s | %s | %s | `%s` |' % (
            c.get('id', '?'),
            c.get('concept', '?'),
            c.get('chapter', '-'),
            link(c.get('doctrine'), c.get('doctrine_exists')),
            link(c.get('implementation'), c.get('implementation_exists')),
            sym_txt,
            test_txt,
            mcp_txt,
            c.get('panel') or '-',
            c.get('status', '?'),
        ))
    a('')

    # -------------------------------------------------------------- the break
    a('## Where the chain is broken')
    a('')
    a('A concept is only finished when every link is present. These are the measured breaks, not '
      'a wishlist.')
    a('')
    a('| ID | Concept | Missing link |')
    a('|---|---|---|')
    broken_any = False
    for c in matrix:
        breaks = []
        if not c.get('doctrine_exists'):
            breaks.append('doctrine file')
        if not c.get('implementation_exists'):
            breaks.append('implementation')
        for s in (c.get('symbols_missing') or []):
            breaks.append('symbol `%s`' % s)
        if c.get('test') and not c.get('test_found'):
            breaks.append('test class `%s`' % c.get('test'))
        if not c.get('test'):
            breaks.append('any test')
        if c.get('mcp_tool') and not c.get('mcp_wired'):
            breaks.append('MCP handshake for `%s`' % c.get('mcp_tool'))
        if breaks:
            broken_any = True
            a('| `%s` | %s | %s |' % (c.get('id'), c.get('concept'), '; '.join(breaks)))
    if not broken_any:
        a('| - | - | none measured |')
    a('')

    # ---------------------------------------------------------- the unwired
    unwired = [c for c in matrix if c.get('mcp_tool')]
    a('## Declared vs wired MCP surface')
    a('')
    a('%d of %d concepts declare an MCP tool. **0 are wired.** The sentinel_hub server exists on '
      'disk, but no handshake has been performed, so every `mcp_wired: false` above is an honest '
      'measurement and not a placeholder. Wiring requires a cross-system action and therefore '
      'explicit R0.' % (len(unwired), len(matrix)))
    a('')
    for c in unwired:
        a('- `%s` %s -> `%s`' % (c.get('id'), c.get('concept'), c.get('mcp_tool')))
    a('')

    # ------------------------------------------------------ next actions
    actions = [(c.get('id'), c.get('concept'), c.get('next_action')) for c in matrix
               if c.get('next_action')]
    a('## Next action per concept (verbatim from the matrix)')
    a('')
    a('These are the *suggestions* half of the brief. They are recorded, not scheduled: scheduling '
      'them is Popy\'s R0, not this script\'s.')
    a('')
    for cid, concept, action in actions:
        a('- **`%s` %s** - %s' % (cid, concept, action))
    a('')

    # -------------------------------------------------------------- gaps
    a('## Gap register (companion)')
    a('')
    if gaps:
        a('%d open gaps, straight from `GAP_REGISTER.json`. The real fields are '
          '`id, area, status, what, evidence, impact, fix_requires, owner` — an '
          'earlier version of this renderer asked for `severity` and `title`, which '
          'do not exist, and so printed `?` for every row while looking fine.'
          % len(gaps))
        a('')
        a('| ID | Area | Status | What | Owner | Fix requires |')
        a('|---|---|---|---|---|---|')
        for g in gaps:
            a('| `%s` | %s | `%s` | %s | %s | %s |' % (
                g.get('id', '?'),
                g.get('area', '-'),
                g.get('status', '-'),
                g.get('what', '-'),
                g.get('owner', '-'),
                g.get('fix_requires', '-')))
        a('')
        a('**Why these are not being fixed silently.** Each one names what it would take, and two '
          'of the three classes require explicit R0 from the operator. A gap that quietly repairs '
          'itself is a gap that was never really a gap.')
    else:
        a('No gaps recorded (unexpected - the matrix builder always emits gaps it has measured).')
    a('')

    # -------------------------------------------------------------- footer
    a('---')
    a('')
    a('**Reading order for a model that has not seen SENTINEL:**')
    a('')
    a('1. [`04_METHOD/TANY_LLM_TO_SENTINEL.md`](04_METHOD/TANY_LLM_TO_SENTINEL.md) - the procedure')
    a('2. [`../07_BACKBONE/skills/tany-llm-to-sentinel.SKILL.md`]'
      '(../07_BACKBONE/skills/tany-llm-to-sentinel.SKILL.md) - the same 12 steps, operational')
    a('3. This file - which of them are actually built')
    a('4. [`02_CHAPTERS/00_CORPUS_INDEX.md`](02_CHAPTERS/00_CORPUS_INDEX.md) - the 17 chapters')
    a('')
    if meta:
        a('Matrix generated: `%s`. Concepts: %d. Gaps: %d.'
          % (meta.get('generated', 'unknown'), len(matrix), len(gaps)))
    a('')
    return '\n'.join(out)


def main() -> int:
    if not MATRIX_JSON.exists():
        print('ERROR: matrix not found: %s' % MATRIX_JSON)
        return 1
    matrix = json.loads(MATRIX_JSON.read_text(encoding='utf-8'))
    if isinstance(matrix, dict):
        meta = matrix.get('meta') or {}
        matrix = matrix.get('concepts') or matrix.get('matrix') or []
    else:
        meta = {}
    gaps = []
    if GAPS_JSON.exists():
        raw = json.loads(GAPS_JSON.read_text(encoding='utf-8'))
        gaps = raw.get('gaps', []) if isinstance(raw, dict) else (raw or [])

    text = render(matrix, gaps, meta)
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    previous = OUT_MD.read_text(encoding='utf-8') if OUT_MD.exists() else None
    changed = previous != text
    # newline='\n' explicitly. Without it, text mode translates every \n to
    # \r\n on Windows, so the file on disk grows by one byte per line and the
    # size this function prints no longer describes the file it just wrote.
    # The number must be true of the artefact, not of the in-memory string.
    with OUT_MD.open('w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    on_disk = OUT_MD.stat().st_size
    printed = len(text.encode('utf-8'))
    if on_disk != printed:
        print('WARNING: on-disk %d B != measured %d B' % (on_disk, printed))
    print('concepts: %d  gaps: %d  bytes: %d  %s'
          % (len(matrix), len(gaps), on_disk,
             'UPDATED' if changed else 'unchanged (idempotent)'))
    return 0


if __name__ == '__main__':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
    sys.exit(main())
